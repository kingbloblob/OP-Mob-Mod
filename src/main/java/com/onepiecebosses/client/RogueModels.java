	/** The basic parts at this rogue's pivots, with no boxes of their own (the boxes are their children). */
	private static PartDefinition[] parts(MeshDefinition mesh, float[] head, float[] body, float[] arm, float[] leg) {
		PartDefinition root = mesh.getRoot();
		PartDefinition headPart = root.addOrReplaceChild("head", CubeListBuilder.create(), PartPose.offset(head[0], head[1], head[2]));
		headPart.addOrReplaceChild("hat", CubeListBuilder.create(), PartPose.ZERO);
		return new PartDefinition[] {
			headPart,
			root.addOrReplaceChild("body", CubeListBuilder.create(), PartPose.offset(body[0], body[1], body[2])),
			root.addOrReplaceChild("right_arm", CubeListBuilder.create(), PartPose.offset(arm[0], arm[1], arm[2])),
			root.addOrReplaceChild("left_arm", CubeListBuilder.create(), PartPose.offset(-arm[0], arm[1], arm[2])),
			root.addOrReplaceChild("right_leg", CubeListBuilder.create(), PartPose.offset(leg[0], leg[1], leg[2])),
			root.addOrReplaceChild("left_leg", CubeListBuilder.create(), PartPose.offset(-leg[0], leg[1], leg[2])),
		};
	}

